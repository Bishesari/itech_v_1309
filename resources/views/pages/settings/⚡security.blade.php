                        <div class="space-y-4">
                            <flux:text variant="subtle">
                                {{ __('با فعال‌سازی احراز هویت دو مرحله‌ای، هنگام ورود از شما یک رمز امن درخواست می‌شود. این رمز از طریق برنامه‌های پشتیبانی‌کننده TOTP روی گوشی شما قابل دریافت است.') }}
